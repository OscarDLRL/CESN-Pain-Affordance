"""Reproduce every experiment and every final figure.

Run from the repository root (conda env `esn`, CUDA):
    python -m CLEAVER_OPTIMIZED.reproduce              # skip stages whose outputs exist
    python -m CLEAVER_OPTIMIZED.reproduce --force      # recompute everything
    python -m CLEAVER_OPTIMIZED.reproduce --only figures evaluation

Stages (in order):
  autoencoder   V6 dual encoder, reference frame 1             ~6 min
  latents       z_static / z_dynamic for all 162 trajectories  ~2 min
  selection     model selection on train+validation only (CV over 7 cleaver locations):
                CESN forward sweeps, perception, discrete SAFE/PAIN inference   ~10 min
  sim           closed loop in ManiSkill on the 18 test pairs  ~3 min
  evaluation    final test evaluation: history, methods, cost  ~5 min
  interpolation off-grid protocol: latents of the 4 off-grid positions, CESN + perception
                refitted on all 9 grid positions, closed loop + evaluation   ~6 min
  figures       outputs/final/{dataset,experiments,interpolation}/   <1 min
Selection never touches the test split; configuration is frozen in config.py.
"""
import argparse
import json
import shutil
import subprocess
import sys
import time

from CLEAVER_OPTIMIZED import config as cfg

AE = cfg.OUT / "autoencoder" / cfg.AE_RUN
FINAL = cfg.OUT / "final"


def py(module, *args):
    cmd = [sys.executable, "-m", module, *map(str, args)]
    print("\n$", " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=cfg.ROOT, check=True)


def stage_autoencoder():
    py("CLEAVER_OPTIMIZED.autoencoder.train", "--run", cfg.AE_RUN)
    py("CLEAVER_OPTIMIZED.analysis.reconstruction", "--checkpoint", AE / "autoencoder.pt")


def stage_latents():
    py("CLEAVER_OPTIMIZED.autoencoder.extract_latents", "--run", cfg.AE_RUN)


def stage_selection():
    py("CLEAVER_OPTIMIZED.analysis.latent_probe", "--ae-runs", cfg.AE_RUN)
    py("CLEAVER_OPTIMIZED.experiments.forward_quality", "--ae-run", cfg.AE_RUN)
    py("CLEAVER_OPTIMIZED.experiments.forward_sweep_cv", "--ae-run", cfg.AE_RUN,
       "--xy-gains", 1, 3, 10, 30, "--fb-gains", 0, 0.1, 0.25, 0.5, 1)
    py("CLEAVER_OPTIMIZED.experiments.forward_sweep_cv", "--ae-run", cfg.AE_RUN, "--name", "forward_sweep_discrete_dyn",
       "--xy-gains", 1, "--fb-gains", 0.5, 1, "--leaks", 0.015, 0.03, 0.06, 0.12, "--radii", 0.6, 0.9, "--ridges", 3, 10, 30)
    py("CLEAVER_OPTIMIZED.experiments.knife_localization")
    py("CLEAVER_OPTIMIZED.experiments.perceived_xy_inversion", "--ae-run", cfg.AE_RUN)


def stage_sim():
    py("CLEAVER_OPTIMIZED.sim.closed_loop")


def stage_evaluation():
    py("CLEAVER_OPTIMIZED.experiments.final_evaluation")


def stage_interpolation():
    py("CLEAVER_OPTIMIZED.autoencoder.extract_latents", "--run", cfg.AE_RUN, "--dataset", cfg.OFFGRID,
       "--name", "latents_offgrid.h5")
    py("CLEAVER_OPTIMIZED.sim.closed_loop", "--protocol", "offgrid")
    py("CLEAVER_OPTIMIZED.experiments.final_evaluation", "--protocol", "offgrid")


def stage_figures():
    py("CLEAVER_OPTIMIZED.analysis.final_figures")


STAGES = {
    "autoencoder": (stage_autoencoder, [AE / "autoencoder.pt"]),
    "latents": (stage_latents, [AE / "latents.h5"]),
    "selection": (stage_selection, [AE / "forward_sweep_discrete_dyn" / "summary.csv", AE / "discrete_cv" / "online_fixed.csv"]),
    "sim": (stage_sim, [cfg.OUT / "sim_closed_loop" / "summary.json"]),
    "evaluation": (stage_evaluation, [FINAL / "results" / "methods.csv"]),
    "interpolation": (stage_interpolation, [FINAL / "interpolation" / "results" / "methods.csv",
                                            cfg.OUT / "sim_closed_loop_offgrid" / "summary.json"]),
    "figures": (stage_figures, [FINAL / "experiments" / "04_methods_comparison.png",
                                FINAL / "interpolation" / "experiments" / "03_methods_comparison.png"]),
}

README = """# Final results (generated by `python -m CLEAVER_OPTIMIZED.reproduce`)

Configuration frozen in `CLEAVER_OPTIMIZED/config.py` before touching the test split.
Test = 2 unseen cleaver positions (K5, K6) x 9 robot starts x {SAFE, PAIN} = 36 trajectories.

## dataset/
- `01_knife_positions.png` - one simulator image with the 9 cleaver positions (train / validation / test)
- `02_robot_initial_positions.png` - the 9 robot start positions

## experiments/
- `01_reconstruction.png` - real frames vs V6 autoencoder reconstruction (test pair, SAFE and PAIN)
- `02_context_history.png` - SAFE/PAIN accuracy as the observed history grows
  (camera every frame vs every 5 frames, deployed)
- `03_computational_cost.png` - wall-clock cost per decision for every method (RTX 3090)
- `04_methods_comparison.png` - CESN batch/incremental, nearest neighbour, linear ridge

## interpolation/ (protocol B: fitted on all 9 grid positions, tested on 4 off-grid positions)
- `dataset/01_offgrid_knife_positions.png` - the 4 off-grid cleaver positions I1-I4
- `experiments/01_reconstruction.png`, `02_context_history.png`, `03_methods_comparison.png`
- `results/` - history, methods, closed-loop summary

## results/
- `history.csv`, `methods.csv`, `cost.csv` - numbers behind the experiment figures
- `sim_closed_loop_summary.json` - closed-loop test in ManiSkill (stop on PAIN detection)
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="recompute even if outputs exist")
    ap.add_argument("--only", nargs="+", choices=list(STAGES), default=list(STAGES))
    a = ap.parse_args()
    for name, (fn, outputs) in STAGES.items():
        if name not in a.only:
            continue
        if not a.force and all(p.exists() for p in outputs):
            print(f"[skip] {name}: outputs exist", flush=True)
            continue
        if a.force and name == "autoencoder" and AE.exists():
            shutil.rmtree(AE)
        t0 = time.perf_counter()
        print(f"[run ] {name}", flush=True)
        fn()
        print(f"[done] {name} in {time.perf_counter() - t0:.0f}s", flush=True)
    (FINAL / "results").mkdir(parents=True, exist_ok=True)
    sim = cfg.OUT / "sim_closed_loop" / "summary.json"
    if sim.exists():
        shutil.copy2(sim, FINAL / "results" / "sim_closed_loop_summary.json")
    isim = cfg.OUT / "sim_closed_loop_offgrid" / "summary.json"
    if isim.exists():
        (FINAL / "interpolation" / "results").mkdir(parents=True, exist_ok=True)
        shutil.copy2(isim, FINAL / "interpolation" / "results" / "sim_closed_loop_summary.json")
    (FINAL / "README.md").write_text(README)
    print("\nFINAL OUTPUTS:", FINAL)
    if sim.exists():
        s = json.loads(sim.read_text())
        print(f"closed loop: PAIN stopped before contact {s['pain_stopped_before_contact_pct']:.0f}% | "
              f"SAFE false stops {s['safe_false_stop_pct']:.0f}% | goal XY {s['goal_xy_error_mm_mean']:.1f} mm")


if __name__ == "__main__":
    main()
